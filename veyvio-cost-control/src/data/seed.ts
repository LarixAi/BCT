function cost(input: {
  id: string
  organisationId: string
  budgetId: string
  supplierName: string
  description: string
  reference: string
  transactionDate: string
  paymentDate?: string | null
  net: number
  vat: number
  vatTreatment?: CostRecord['vatTreatment']
  status: CostRecord['status']
  category: CostRecord['category']
  subcategory?: CostRecord['subcategory']
  vehicleId?: string
  costCentreId?: string
  evidence: string
  sourceKey: string
  now: string
  reviewOpen?: boolean
  reviewRejected?: boolean
  validationState?: CostRecord['validationState']
}): CostRecord {
  const gross = input.net + input.vat
  let reviewState: CostRecord['reviewState'] = 'none'
  if (input.reviewRejected) reviewState = 'rejected'
  else if (input.reviewOpen) reviewState = 'open'

  return {
    id: input.id,
    organisationId: input.organisationId,
    version: 1,
    supplierName: input.supplierName,
    description: input.description,
    reference: input.reference,
    transactionDate: input.transactionDate,
    paymentDate: input.paymentDate === undefined ? input.transactionDate : input.paymentDate,
    accountingPeriod: input.transactionDate.slice(0, 7),
    net: { amountMinor: input.net, currency: 'GBP' },
    vat: { amountMinor: input.vat, currency: 'GBP' },
    gross: { amountMinor: gross, currency: 'GBP' },
    vatTreatment: input.vatTreatment ?? null,
    status: input.status,
    category: input.category,
    subcategory: input.subcategory ?? null,
    allocations: [
      {
        budgetId: input.budgetId,
        category: input.category,
        vehicleId: input.vehicleId ?? null,
        costCentreId: input.costCentreId ?? 'cc_ops',
        supplierId: null,
        amountMinor: gross,
      },
    ],
    validationState: input.validationState ?? 'reconciled',
    reviewState,
    evidence: input.evidence
      ? [{ id: `${input.id}_ev`, label: input.evidence, sourceType: 'csv' }]
      : [],
    sourceKey: input.sourceKey,
    linkedCommitmentId: null,
    createdAt: input.now,
    updatedAt: input.now,
  }
}
